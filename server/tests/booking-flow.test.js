import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import express from 'express';
import auth from '../src/routes/auth.js';
import bookings from '../src/routes/bookingRoutes.js';
import shows from '../src/routes/showtimeRoutes.js';
import admin from '../src/routes/adminRoutes.js';
import pool from '../src/config/db.js';
import { cleanExpiredHolds } from '../src/services/seatHoldService.js';

test('MySQL: competing holds, ownership, payment retry, QR, expiry and cancellation', async () => {
  const app = express(); app.use(express.json()); app.use('/api/auth', auth); app.use('/api/bookings', bookings); app.use('/api/showtimes', shows); app.use('/api/admin', admin);
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = 'http://127.0.0.1:' + server.address().port;
  const users = []; let showId, productId;
  async function request(path, body, cookie, method) {
    const res = await fetch(base + '/api/' + path, { method: method || (body ? 'POST' : 'GET'), headers: { ...(body && {'Content-Type':'application/json'}), ...(cookie && { Cookie: cookie }) }, ...(body && { body: JSON.stringify(body) }) });
    const value = await res.json();
    return { status: res.status, body: value, data: value.data, cookie: res.headers.getSetCookie().find(v => /^nova_session=[^;]/.test(v))?.split(';')[0], cookies: res.headers.getSetCookie() };
  }
  const ok = r => { assert.equal(r.status, 200, JSON.stringify(r.body)); return r.data; };
  try {
    for (let i=0;i<3;i++) {
      const email = 'booking-test-' + randomUUID() + '@example.invalid', password = randomUUID() + '!';
      const registered = await request('auth/register', { fullName: 'Booking integration test', email, password });
      assert.equal(registered.status, 201, JSON.stringify(registered.body));
      const [rows] = await pool.query('SELECT id FROM users WHERE email=?', [email]);
      users.push({ id:rows[0].id, email });
      const login = await request('auth/login', { account:email, password }); ok(login);
      assert.ok(login.cookies.some(v => /^nova_session=[^;]/.test(v) && /Path=\/api;/.test(v)));
      users[i].cookie = login.cookie;
    }
    assert.equal((await request('admin/products')).status, 401);
    assert.equal((await request('admin/overview', null, users[0].cookie)).status, 403);
    await pool.query("UPDATE users SET role='admin' WHERE id=?", [users[2].id]);
    const adminCookie = users[2].cookie;
    const product = { code: 'TEST-' + randomUUID().slice(0, 30), name: 'Combo kiểm thử TV4', category: 'combo', description: 'Temporary test fixture', price: 45000, image: '/images/test.jpg', isActive: true };
    assert.equal((await request('admin/products', { ...product, price: -1 }, adminCookie)).status, 400);
    assert.equal((await request('admin/products', product, users[0].cookie)).status, 403);
    const createdProduct = await request('admin/products', product, adminCookie);
    assert.equal(createdProduct.status, 201, JSON.stringify(createdProduct.body)); productId = createdProduct.data.id;
    assert.equal((await request('admin/products', product, adminCookie)).status, 409);
    assert.equal(ok(await request('admin/products', null, adminCookie)).find(p => p.id === productId).price, 45000);
    const baseline = ok(await request('admin/overview', null, adminCookie)).totals;
    assert.equal((await request('admin/overview?from=2026-02-30', null, adminCookie)).status, 400);
    assert.equal((await request('admin/orders?page=-1', null, adminCookie)).status, 400);
    const [fixture] = await pool.query('SELECT s.room_id, m.id AS movie_id FROM seats s CROSS JOIN movies m WHERE s.is_active=TRUE AND m.is_visible=TRUE ORDER BY s.id,m.id LIMIT 1');
    assert.ok(fixture[0], 'Import database seed first');
    const f = fixture[0];
    const [insert] = await pool.query("INSERT INTO showtimes(movie_id,room_id,starts_at,ends_at,base_price,is_demo) VALUES (?,?,DATE_ADD(NOW(),INTERVAL 40 DAY),DATE_ADD(NOW(),INTERVAL 41 DAY),90000,TRUE)", [f.movie_id, f.room_id]);
    showId = insert.insertId;
    const [seats] = await pool.query('SELECT id FROM seats WHERE room_id=? ORDER BY id LIMIT 3', [f.room_id]);
    for (const seat of seats) await pool.query('INSERT INTO showtime_seats(showtime_id,seat_id,room_id,price) VALUES (?,?,?,90000)', [showId,seat.id,f.room_id]);
    const seatId = seats[0].id;
    assert.equal(ok(await request('showtimes/' + showId + '/seats')).seats.length, 3);
    assert.equal((await request('bookings/hold-seats', {showtimeId:showId,seatIds:[seatId]})).status, 401);
    assert.equal((await request('bookings/hold-seats', {showtimeId:showId,seatIds:[seatId,seatId]}, users[0].cookie)).status, 400);
    const race = await Promise.all(users.slice(0,2).map(u => request('bookings/hold-seats', {showtimeId:showId,seatIds:[seatId],userId:users[1].id}, u.cookie)));
    assert.deepEqual(race.map(r => r.status).sort(), [200,409]);
    const winner = race.findIndex(r => r.status === 200), user = users[winner], other = users[1-winner];
    const hold = race[winner].data;
    assert.equal(String(hold.userId), String(user.id)); assert.ok(hold.remainingSeconds > 175 && hold.remainingSeconds <= 180);
    assert.equal((await request('bookings/holds/' + hold.holdId, null, other.cookie)).status, 404);
    assert.equal((await request('bookings/release-hold', {holdId:hold.holdId}, other.cookie)).status, 404);
    const items = [{productId,quantity:2}], total = 180000;
    ok(await request('admin/products/' + productId, { ...product, isActive: false }, adminCookie, 'PUT'));
    assert.equal((await request('bookings/confirm', {holdId:hold.holdId,items,expectedTotal:total}, user.cookie)).status, 409);
    ok(await request('admin/products/' + productId, product, adminCookie, 'PUT'));
    assert.equal((await request('bookings/confirm', {holdId:hold.holdId,items,expectedTotal:1}, user.cookie)).status, 409);
    const invoice = ok(await request('bookings/confirm', {holdId:hold.holdId,items,expectedTotal:total}, user.cookie));
    let [inventory] = await pool.query('SELECT state FROM showtime_seats WHERE showtime_id=? AND seat_id=?', [showId,seatId]);
    assert.equal(inventory[0].state, 'held');
    const payPath = 'bookings/' + invoice.bookingId + '/pay';
    const failed = {method:'momo',outcome:'failure',requestId:randomUUID(),expectedTotal:total};
    assert.equal(ok(await request(payPath, failed, user.cookie)).status, 'payment_failed');
    assert.equal(ok(await request('bookings', null, user.cookie)).length, 0);
    const failedHistory = ok(await request('bookings?status=all', null, user.cookie));
    assert.equal(failedHistory.length, 1); assert.equal(failedHistory[0].status, 'payment_failed'); assert.equal(failedHistory[0].ticketCode, null);
    assert.equal(Number(ok(await request('admin/overview', null, adminCookie)).totals.revenue), Number(baseline.revenue));
    const payment = {method:'momo',outcome:'success',requestId:randomUUID(),expectedTotal:total};
    assert.equal((await request(payPath, payment, other.cookie)).status, 404);
    const paidResults = await Promise.all([request(payPath,payment,user.cookie),request(payPath,payment,user.cookie)]);
    paidResults.forEach(r => assert.equal(ok(r).status,'paid'));
    const [payments] = await pool.query('SELECT COUNT(*) AS count FROM payments WHERE booking_id=?', [invoice.bookingId]);
    assert.equal(Number(payments[0].count),2);
    [inventory] = await pool.query('SELECT state,hold_id FROM showtime_seats WHERE showtime_id=? AND seat_id=?', [showId,seatId]);
    assert.equal(inventory[0].state,'booked'); assert.equal(inventory[0].hold_id,null);
    const receipt = ok(await request('bookings/' + invoice.bookingCode,null,user.cookie));
    assert.equal(receipt.total,total); assert.equal(receipt.items[0].quantity,2); assert.match(receipt.ticketCode,/^NOVA-/); assert.equal(receipt.source,'database');
    assert.equal(receipt.seatLines[0].unitPrice, 90000); assert.ok(receipt.paidAt); assert.equal(receipt.payments.length, 2);
    ok(await request('admin/products/' + productId, { ...product, name: 'Đã đổi tên', price: 99000, isActive: false }, adminCookie, 'PUT'));
    const adminReceipt = ok(await request('admin/orders/' + invoice.bookingCode, null, adminCookie));
    assert.equal(adminReceipt.items[0].name, product.name); assert.equal(adminReceipt.items[0].unitPrice, 45000);
    assert.equal(adminReceipt.ticketCode, receipt.ticketCode);
    const overview = ok(await request('admin/overview', null, adminCookie));
    assert.equal(Number(overview.totals.revenue) - Number(baseline.revenue), total);
    assert.equal(Number(overview.totals.tickets) - Number(baseline.tickets), 90000);
    assert.equal(Number(overview.totals.products) - Number(baseline.products), 90000);
    assert.equal(Number(overview.totals.seats) - Number(baseline.seats), 1);
    const orderList = ok(await request('admin/orders?q=' + invoice.bookingCode + '&status=paid', null, adminCookie));
    assert.equal(orderList.total, 1); assert.equal(orderList.orders[0].orderCode, invoice.bookingCode);
    assert.equal((await request('admin/orders/' + invoice.bookingCode, null, other.cookie)).status, 403);
    assert.equal(ok(await request('bookings',null,user.cookie)).length,1);
    assert.equal(ok(await request('bookings',null,other.cookie)).length,0);
    assert.equal((await request('bookings/' + invoice.bookingCode,null,other.cookie)).status,404);
    assert.equal((await request('bookings/release-hold',{holdId:hold.holdId},user.cookie)).status,409);
    assert.equal((await request('bookings/hold-seats',{showtimeId:showId,seatIds:[seatId]},other.cookie)).status,409);
    const cancelHold = ok(await request('bookings/hold-seats',{showtimeId:showId,seatIds:[seats[1].id]},user.cookie));
    const cancelOrder = ok(await request('bookings/confirm',{holdId:cancelHold.holdId,expectedTotal:90000},user.cookie));
    ok(await request('bookings/release-hold',{holdId:cancelHold.holdId},user.cookie));
    assert.equal(ok(await request('bookings?status=all', null, user.cookie)).find(o => o.orderCode === cancelOrder.bookingCode).status, 'cancelled');
    assert.equal((await request('bookings/' + cancelOrder.bookingId + '/pay',{...payment,requestId:randomUUID(),expectedTotal:90000},user.cookie)).status,409);
    // Isolated expired fixture: never alter a real customer's hold to test timeout.
    const [expired] = await pool.query("INSERT INTO seat_holds(user_id,showtime_id,created_at,expires_at) VALUES (?,?,DATE_SUB(NOW(),INTERVAL 4 MINUTE),DATE_SUB(NOW(),INTERVAL 1 MINUTE))",[user.id,showId]);
    await pool.query("UPDATE showtime_seats ss JOIN seat_holds h ON h.id=? SET ss.state='held',ss.hold_id=h.id,ss.held_until=h.expires_at WHERE ss.showtime_id=? AND ss.seat_id=?",[expired.insertId,showId,seats[2].id]);
    const expiredCode = 'TEST-' + randomUUID().slice(0, 25);
    await pool.query('INSERT INTO bookings(booking_code,user_id,showtime_id,hold_id,ticket_subtotal,product_subtotal,total_amount) VALUES (?,?,?,?,90000,0,90000)', [expiredCode,user.id,showId,expired.insertId]);
    await cleanExpiredHolds();
    assert.equal(ok(await request('bookings/holds/' + expired.insertId,null,user.cookie)).status,'expired');
    assert.equal((await request('bookings/confirm',{holdId:expired.insertId,expectedTotal:90000},user.cookie)).status,409);
    const [released] = await pool.query('SELECT state FROM showtime_seats WHERE showtime_id=? AND seat_id=?',[showId,seats[2].id]);
    assert.equal(released[0].state,'available');
    const expiredReceipt = ok(await request('bookings/' + expiredCode, null, user.cookie));
    assert.equal(expiredReceipt.status, 'expired'); assert.equal(expiredReceipt.ticketCode, null);
    assert.equal(ok(await request('bookings?status=all', null, user.cookie)).length, 3);
    assert.equal(Number(ok(await request('admin/overview', null, adminCookie)).totals.revenue) - Number(baseline.revenue), total);
  } finally {
    if (showId) {
      for (const table of ['payments','booking_items','booking_seats']) await pool.query('DELETE t FROM ' + table + ' t JOIN bookings b ON b.id=t.booking_id WHERE b.showtime_id=?',[showId]);
      await pool.query('DELETE FROM showtime_seats WHERE showtime_id=?',[showId]);
      await pool.query('DELETE FROM bookings WHERE showtime_id=?',[showId]);
      await pool.query('DELETE FROM seat_holds WHERE showtime_id=?',[showId]);
      await pool.query('DELETE FROM showtimes WHERE id=?',[showId]);
    }
    if (productId) await pool.query('DELETE FROM products WHERE id=?', [productId]);
    for (const user of users) await pool.query('DELETE FROM users WHERE id=? AND email=?',[user.id,user.email]);
    await new Promise(resolve => server.close(resolve)); await pool.end();
  }
});
